// Optional development check. Runtime skill has no Node/Playwright dependency.
// PLAYWRIGHT_MODULE=/absolute/path/to/playwright/index.mjs node tests/browser-smoke.mjs
import assert from 'node:assert/strict';
import {spawn, execFileSync} from 'node:child_process';
import {mkdtemp, readFile, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const {chromium} = await import(process.argv[2] || process.env.PLAYWRIGHT_MODULE || 'playwright');
const skill = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = path.join(skill, 'scripts/report_workflow.py');
const work = await mkdtemp(path.join(tmpdir(), 'weekly-report-browser-'));
const python = process.env.REPORT_PYTHON || 'python3';
const period = {id:'2026-W42', type:'weekly',start:'2026-10-12',end:'2026-10-18',as_of:'2026-10-18'};
const base = {department:'研发部',owner:'张工',criteria:'验收单签署',deadline:'2026-10-16',metric:null};
const metric = {target:100,unit:'万元',definition:'已签字验收金额',direction:'at_least',aggregation:'incremental',period_start:'2026-10-12',period_end:'2026-10-18'};
const fixture = {period,goals:[{...base,id:'G1',title:'客户验收'},{...base,id:'G2',title:'展会材料',department:'市场部',deadline:'2026-10-20'},{...base,id:'G3',title:'验收金额',deadline:'2026-10-25',metric}],observations:{G1:{status:'in_progress',progress:'联调完成',forecast_date:'2026-10-20'},G3:{status:'in_progress',progress:'待确认验收金额',...Object.fromEntries(Object.entries(metric).filter(([k])=>!['target','direction'].includes(k)))}},sources:[]};
const input = path.join(work,'input.json');
await writeFile(input,JSON.stringify(fixture));
execFileSync(python,[script,'prepare','--workdir',work,'--input',input]);
const server=spawn(python,[script,'serve','--workdir',work,'--period',period.id,'--no-browser'],{stdio:['ignore','pipe','pipe']});
let browser, stderr='', serverOutput='';
server.stderr.on('data',data=>stderr+=data.toString());
try {
  const url = await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error(`server did not start: ${stderr}`)),10000);
    server.stdout.on('data',data=>{serverOutput+=data.toString();const line=serverOutput.split('\n').find(s=>s.startsWith('{'));if(!line)return;try{const output=JSON.parse(line);clearTimeout(timer);resolve(output.url);}catch{}});
    server.once('exit',code=>{clearTimeout(timer);reject(new Error(`server exit ${code}: ${stderr}`));});
  });
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1360,height:980}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'客户验收',exact:true}).first().waitFor();
  for(const id of ['G1','G2','G3']) await page.locator(`#input-baseline-${id}-confirmation`).check();
  await page.locator('#input-progress-G1-action').fill('协调客户开放环境');
  await page.locator('#input-progress-G1-action_owner').fill('李经理');
  await page.locator('#input-progress-G1-action_deadline').fill('2026-10-19');
  await page.locator('#unknown-progress-G1-reason').check();
  await page.getByRole('button',{name:'提交确认并继续生成'}).click();
  await page.locator('#errors').waitFor({state:'visible'});
  assert.match(await page.locator('#errors').innerText(),/须说明原因/);
  await page.getByLabel('客户验收：偏差原因暂无法提供的原因',{exact:true}).fill('客户尚未回复，周一跟进');
  await page.locator('#input-progress-G2-status').selectOption('completed');
  await page.locator('#input-progress-G2-actual_date').waitFor({state:'visible'});
  await page.locator('#input-progress-G2-actual_date').fill('2026-10-17');
  await page.locator('#input-progress-G2-progress').fill('展会材料已交付并验收');
  await page.locator('#input-metric-G3-actual').fill('90');
  await page.locator('#input-progress-G3-reason').waitFor({state:'visible'});
  for(const [key,value] of [['reason','本期验收材料尚待客户签署'],['action','跟进剩余验收单'],['action_owner','张工'],['action_deadline','2026-10-23'],['forecast_date','2026-10-23']]) await page.locator(`#input-progress-G3-${key}`).fill(value);
  await page.getByRole('button',{name:'保存草稿',exact:true}).click();
  await page.getByText('草稿已保存',{exact:true}).waitFor();
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('#input-metric-G3-actual').inputValue(),'90');
  assert.equal(await page.locator('#input-baseline-G1-confirmation').isChecked(),true);
  assert.equal(await page.getByLabel('客户验收：偏差原因暂无法提供的原因',{exact:true}).inputValue(),'客户尚未回复，周一跟进');
  await page.getByRole('button',{name:'＋ 添加目标',exact:true}).click();
  const added=page.locator('.new-card');
  for(const [label,value] of [['目标名称','下周发布方案'],['责任部门','产品部'],['负责人','王工'],['截止日期','2026-10-23'],['验收标准 / 预期结果','方案评审通过'],['本期进展（下期新计划请写明尚未启动）','下期新计划，尚未启动']]) await added.getByLabel(label,{exact:true}).fill(value);
  await added.getByLabel('本期状态',{exact:true}).selectOption('not_started');
  await added.getByLabel('确认将该目标及时间节点纳入持续跟踪').check();
  await page.getByRole('button',{name:'保存草稿',exact:true}).click();
  await page.getByText('草稿已保存',{exact:true}).waitFor();
  await page.screenshot({path:path.join(work,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(work,'mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.getByRole('button',{name:'提交确认并继续生成',exact:true}).click();
  await page.getByText('确认已提交',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'提交确认并继续生成',exact:true}).isDisabled(),true);
  const analysis=JSON.parse(execFileSync(python,[script,'merge','--workdir',work,'--period',period.id],{encoding:'utf-8'}));
  assert.equal(analysis.tracked,4);
  assert.equal(analysis.items.find(r=>r.goal.id==='G1').schedule,'overdue');
  assert.equal(analysis.items.find(r=>r.goal.id==='G2').schedule,'early');
  assert.equal(analysis.items.find(r=>r.goal.id==='G3').metric_comparison.actual,90);
  assert.equal(analysis.unresolved[0].field,'reason');
  const report=path.join(work,'2026-W42-周报.md');
  await writeFile(report,'# 周报 — 2026-10-12 至 2026-10-18\n\n客户验收延期 2 天；展会材料提前交付；验收金额 90 万元，目标 100 万元；下周发布方案尚未启动。\n\n客户验收的延期原因尚待客户确认。\n');
  execFileSync(python,[script,'finalize','--workdir',work,'--period',period.id,'--report',report]);
  const final=JSON.parse(await readFile(path.join(work,'.weekly-report/periods/2026-W42/session.json'),'utf-8'));
  assert.equal(final.status,'generated');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({status:'PASS',work,checks:['逐项目标确认','未知原因必填','条件完成日期','草稿刷新恢复','独立新增计划','手机无横向溢出','提交后锁定','继续合并分析并归档'],screenshots:['desktop.png','mobile.png']},null,2));
} finally {
  if(browser) await browser.close();
  server.kill('SIGINT');
}
